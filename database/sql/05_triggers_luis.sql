-- Trigger 1

CREATE OR REPLACE FUNCTION oficina_mecanica.fn_validar_estoque_peca()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estoque < 0 THEN
        RAISE EXCEPTION 'O estoque da peca nao pode ser negativo';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_luis_validar_estoque
ON oficina_mecanica.peca;

CREATE TRIGGER trg_luis_validar_estoque
BEFORE INSERT OR UPDATE
ON oficina_mecanica.peca
FOR EACH ROW
EXECUTE FUNCTION oficina_mecanica.fn_validar_estoque_peca();


-- TRIGGER 2

CREATE TABLE IF NOT EXISTS oficina_mecanica.historico_status_pagamento_luis (
    id_historico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagamento_id INTEGER NOT NULL,
    status_anterior VARCHAR(30) NOT NULL,
    status_novo VARCHAR(30) NOT NULL,
    data_alteracao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION oficina_mecanica.fn_auditar_status_pagamento_luis()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO oficina_mecanica.historico_status_pagamento_luis (
        pagamento_id,
        status_anterior,
        status_novo
    )
    VALUES (
        NEW.id_pagamento,
        OLD.status,
        NEW.status
    );

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_luis_auditar_pagamento
ON oficina_mecanica.pagamento;

CREATE TRIGGER trg_luis_auditar_pagamento
AFTER UPDATE OF status
ON oficina_mecanica.pagamento
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION oficina_mecanica.fn_auditar_status_pagamento_luis();
